/**
 * Turns the original photos in media-src/ into small WebP files in public/media/
 * (a full size up to 1600px plus 480px and 800px versions for phones and grid thumbnails),
 * and writes src/data/images.gen.ts with their sizes so <img> can use srcset and
 * reserve space before the image arrives. The 3D material scans in media-src/textures
 * become WebP in public/textures.
 *
 * Run after adding or replacing a photo:  npm run images
 */
import { mkdir, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..");
const SRC = path.join(ROOT, "media-src");
const OUT = path.join(ROOT, "public", "media");
const FULL = 1600;
const SMALL = [480, 800];
const QUALITY = 72;

async function* walk(dir, skip = []) {
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (!skip.includes(e.name)) yield* walk(p);
    } else if (/\.(jpe?g|png)$/i.test(e.name)) yield p;
  }
}

/* 3D material scans (media-src/textures -> public/textures): same size, WebP, sharper for normal maps */
const TEX_SRC = path.join(SRC, "textures");
const TEX_OUT = path.join(ROOT, "public", "textures");
await mkdir(TEX_OUT, { recursive: true });
for await (const file of walk(TEX_SRC)) {
  const name = path.basename(file).replace(/\.(jpe?g|png)$/i, "");
  const quality = name.endsWith("_n") ? 82 : 80;
  const out = await sharp(file).webp({ quality, effort: 6 }).toFile(path.join(TEX_OUT, `${name}.webp`));
  console.log(`textures/${name}: ${(out.size / 1024).toFixed(0)} KB`);
}

const manifest = {};
for await (const file of walk(SRC, ["textures", "unused-hdr"])) {
  const rel = path.relative(SRC, file).replace(/\\/g, "/").replace(/\.(jpe?g|png)$/i, "");
  await mkdir(path.dirname(path.join(OUT, rel)), { recursive: true });
  const img = sharp(file).rotate();
  const full = await img.clone().resize({ width: FULL, height: FULL, fit: "inside", withoutEnlargement: true }).webp({ quality: QUALITY, effort: 6, smartSubsample: true }).toFile(path.join(OUT, `${rel}.webp`));
  const entry = { w: full.width, h: full.height, small: [] };
  for (const w of SMALL) {
    if (full.width < w * 1.25) continue;
    await img.clone().resize({ width: w }).webp({ quality: QUALITY, effort: 6, smartSubsample: true }).toFile(path.join(OUT, `${rel}-${w}.webp`));
    entry.small.push(w);
  }
  manifest[`/media/${rel}.webp`] = entry;
  console.log(`${rel}: ${full.width}x${full.height} ${(full.size / 1024).toFixed(0)} KB`);
}

const body = `// Generated by scripts/optimize-images.mjs. Do not edit by hand: run \`npm run images\`.
/** Pixel size of each photo in /public/media; \`small\` lists the widths of its -<width>.webp versions. */
export const IMAGES: Record<string, { w: number; h: number; small: number[] }> = ${JSON.stringify(manifest)};
`;
await writeFile(path.join(ROOT, "src", "data", "images.gen.ts"), body);
